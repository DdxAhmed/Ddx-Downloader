export type MediaProviderType = 'youtube' | 'instagram' | 'vimeo' | 'tiktok' | 'facebook' | 'generic';

export interface MediaFormat {
  formatId: string;
  ext: string;
  resolution?: string;
  height?: number;
  width?: number;
  fps?: number;
  vcodec?: string;
  acodec?: string;
  filesize?: number;
  tbr?: number;
  qualityLabel: string;
  isVideoOnly: boolean;
  isAudioOnly: boolean;
  isMuxed: boolean;
}

export interface SubtitleTrack {
  language: string;
  name: string;
  ext: string;
  isAutoGenerated: boolean;
}

export interface PlaylistItem {
  id: string;
  index: number;
  title: string;
  url: string;
  duration?: number;
  thumbnail?: string;
  uploader?: string;
}

export interface MediaInfo {
  id: string;
  url: string;
  title: string;
  description?: string;
  thumbnail?: string;
  uploader?: string;
  uploaderUrl?: string;
  duration?: number;
  platform: MediaProviderType;
  isPlaylist: boolean;
  playlistTitle?: string;
  playlistItemCount?: number;
  playlistItems?: PlaylistItem[];
  formats: MediaFormat[];
  subtitles: SubtitleTrack[];
}

export type JobStatus = 'queued' | 'downloading' | 'processing' | 'completed' | 'failed' | 'cancelled' | 'paused';

export interface DownloadJob {
  id: string;
  sourceUrl: string;
  sourcePlatform: string;
  mediaTitle: string;
  thumbnailUrl?: string;
  mediaDuration?: number;
  selectedFormat: string;
  selectedQuality: string;
  isAudioOnly: boolean;
  targetContainer: string;
  outputPath: string;
  status: JobStatus;
  progress: number;
  downloadedBytes: number;
  totalBytes: number;
  downloadSpeed: string;
  eta: string;
  errorMessage?: string;
  createdAt: string;
  startedAt?: string;
  completedAt?: string;
  isPlaylist?: boolean;
  playlistTitle?: string;
  playlistIndex?: number;
  selectedSubtitles?: string[];
  embedSubtitles?: boolean;
}

export interface DownloadHistoryEntry {
  id: string;
  jobId: string;
  mediaTitle: string;
  sourceUrl: string;
  sourcePlatform: string;
  filePath: string;
  fileSize: number;
  format: string;
  duration: number;
  thumbnailUrl?: string;
  completedAt: string;
}

export interface AppSettings {
  downloadDirectory: string;
  preferredQuality: string;
  preferredContainer: string;
  defaultAudioFormat: string;
  maxConcurrentDownloads: number;
  theme: 'dark' | 'light';
  language: string;
  embedSubtitles: boolean;
  downloadSubtitles: boolean;
  customYtDlpPath?: string;
  customFfmpegPath?: string;
}

export interface DependencyStatusItem {
  available: boolean;
  version?: string;
  path?: string;
  error?: string;
}

export interface DependencyStatus {
  ytDlp: DependencyStatusItem;
  ffmpeg: DependencyStatusItem;
}

export interface CreateDownloadRequest {
  url: string;
  title: string;
  thumbnail?: string;
  duration?: number;
  platform: string;
  formatId: string;
  qualityLabel: string;
  isAudioOnly: boolean;
  container: string;
  customSubfolder?: string;
  playlistTitle?: string;
  playlistIndex?: number;
  selectedSubtitles?: string[];
  embedSubtitles?: boolean;
}

export interface PlaylistBatchDownloadRequest {
  playlistTitle: string;
  items: Array<{
    url: string;
    title: string;
    thumbnail?: string;
    duration?: number;
    index: number;
  }>;
  qualityLabel: string;
  formatId: string;
  isAudioOnly: boolean;
  container: string;
  organizeInFolder: boolean;
}

export interface AppInfo {
  version: string;
  platform: string;
  userDataPath: string;
  downloadsPath: string;
}

export type UpdateStatus =
  | 'idle'
  | 'checking'
  | 'available'
  | 'not-available'
  | 'downloading'
  | 'downloaded'
  | 'error';

export interface UpdateInfo {
  version: string;
  releaseName?: string;
  releaseNotes?: string;
  releaseDate?: string;
}

export interface UpdateProgress {
  bytesPerSecond: number;
  percent: number;
  total: number;
  transferred: number;
}

export interface UpdateState {
  status: UpdateStatus;
  currentVersion: string;
  updateInfo?: UpdateInfo | null;
  progress?: UpdateProgress | null;
  error?: string | null;
  lastChecked?: string | null;
  isManualCheck?: boolean;
}

export interface ElectronAPI {
  analyzeUrl: (url: string) => Promise<{ success: boolean; data?: MediaInfo; error?: string }>;
  startDownload: (request: CreateDownloadRequest) => Promise<{ success: boolean; jobId?: string; error?: string }>;
  startPlaylistDownload: (request: PlaylistBatchDownloadRequest) => Promise<{ success: boolean; jobIds?: string[]; error?: string }>;
  cancelDownload: (jobId: string) => Promise<{ success: boolean; error?: string }>;
  retryDownload: (jobId: string) => Promise<{ success: boolean; error?: string }>;
  getQueue: () => Promise<DownloadJob[]>;
  clearCompletedQueue: () => Promise<{ success: boolean }>;
  getHistory: () => Promise<DownloadHistoryEntry[]>;
  deleteHistoryEntry: (id: string, deleteFile?: boolean) => Promise<{ success: boolean; error?: string }>;
  clearHistory: () => Promise<{ success: boolean }>;
  getSettings: () => Promise<AppSettings>;
  updateSettings: (settings: Partial<AppSettings>) => Promise<{ success: boolean; settings: AppSettings }>;
  selectDirectory: () => Promise<{ success: boolean; path?: string }>;
  checkDependencies: () => Promise<DependencyStatus>;
  openFile: (filePath: string) => Promise<{ success: boolean; error?: string }>;
  openFolder: (filePath: string) => Promise<{ success: boolean; error?: string }>;
  openExternal: (url: string) => Promise<{ success: boolean }>;
  getAppInfo: () => Promise<AppInfo>;
  onDownloadProgress: (callback: (job: DownloadJob) => void) => () => void;
  onQueueUpdated: (callback: (queue: DownloadJob[]) => void) => () => void;
  onDependencyStatusChanged: (callback: (status: DependencyStatus) => void) => () => void;
  // Updater
  checkForUpdates: (isManual?: boolean) => Promise<{ success: boolean; error?: string }>;
  downloadUpdate: () => Promise<{ success: boolean; error?: string }>;
  installUpdate: () => Promise<{ success: boolean; error?: string }>;
  getUpdateState: () => Promise<UpdateState>;
  onUpdateStateChanged: (callback: (state: UpdateState) => void) => () => void;
}

declare global {
  interface Window {
    electronAPI: ElectronAPI;
  }
}

